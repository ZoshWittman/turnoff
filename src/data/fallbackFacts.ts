export function factsForCategory(category: FactCategory): Fact[] {
  return FALLBACK_FACTS.filter((fact) => fact.category === category);
}

export function randomFallbackFact(
  category?: FactCategory,
  excludeIds: string[] = [],
): Fact {
  const pool = (category ? factsForCategory(category) : FALLBACK_FACTS).filter(
    (fact) => !excludeIds.includes(fact.id),
  );
  const list = pool.length > 0 ? pool : FALLBACK_FACTS;
  const pick = list[Math.floor(Math.random() * list.length)]!;
  return { ...pick, createdAt: new Date().toISOString() };
}
